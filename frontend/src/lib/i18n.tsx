const DICT = { uz, ru, en }
export type Key = keyof typeof uz

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (k: Key, v?: Record<string, any>) => string }>(null as any)

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useLocalStorage<Lang>('saff.lang', 'uz')
  const value = useMemo(() => ({
    lang,
    setLang,
    t: (k: Key, v?: Record<string, any>) => {
      let s: string = (DICT[lang] as any)[k] ?? (uz as any)[k] ?? String(k)
      if (v) for (const [key, val] of Object.entries(v)) s = s.replace(`{${key}}`, String(val))
      return s
    },
  }), [lang])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export const useT = () => useContext(Ctx)
